import type { Device, DeviceComponent } from '../types'
import { expandBOMToSlots, findBOMById } from './assembly-helpers'

// Build a realistic component slot list for a server assembly from its BOM and
// decorate each slot with a deterministic serial number. Used by the newer
// server samples below so we don't repeat 12-line component arrays per device.
function serverComponents(deviceId: string, bomId: string, serialPrefix: string): DeviceComponent[] {
  const bom = findBOMById(bomId)
  if (!bom) return []
  return expandBOMToSlots(bom, deviceId).map((s, idx) => ({
    ...s,
    serialNumber: `${serialPrefix}-${String(idx + 1).padStart(3, '0')}`,
  }))
}

